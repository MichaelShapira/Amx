const STEPS: [string, string][] = [
  ["Plan", "The wizard's choices become a run definition (run.yaml). The pre-check Lambda resolves every cell (model × hardware option × number format), checks the request pools, the instance types' availability and price, and the Hugging Face token for gated models; a run that cannot work is refused with the reason."],
  ["Launch", "target_control launches one EC2 instance per hardware option from its launch template (Spot first, On-Demand after the waiting time you set), tagged bench:managed. At boot the host syncs the host scripts from s3://…/artifacts/host/, starts the CloudWatch agent and uploads its facts (CPU flags, kernel, driver)."],
  ["Stage the model", "stage_model.sh puts the pinned Hugging Face revision under /opt/models: from the S3 cache when it is there, otherwise downloaded from the Hub (every LFS file checked against the sha256 the Hub reports) and then cached for the next run. The token is read from Secrets Manager into a 0600 tmpfs file only for gated repositories."],
  ["Convert, when the engine needs it", "OpenVINO number formats (BF16-OV, INT8, INT4) are not run from the Hugging Face files: the export container turns the checkpoint into OpenVINO IR, compressing weights where asked. The result is cached in S3 under a hash of the arguments, the source revision and the tool versions. vLLM and PyTorch read the checkpoint as-is."],
  ["Serve", "serve.sh runs the engine image with the cell's options (port, environment, model directory, GPU access), waits for the health endpoint, then sends one real request; the run page shows the server's answer when that fails."],
  ["Probe", "On CPU hosts the AMX probe captures a oneDNN / OpenVINO trace of one request and perf counters (exe.amx_busy) during the measurements, so a CPU result is marked AMX VERIFIED only when the matrix math really ran on AMX; a memory-bandwidth probe (STREAM) records the host's ceiling."],
  ["Measure", "For every load setting the level state machine warms the server up, then worker Lambdas send the pool's requests at the set concurrency (or batch size), recording per-request timings and token counts; repeats are pooled. aggregate_level summarizes each measurement and reads the host's utilization from CloudWatch; aggregate_run writes the report."],
  ["Tear down", "Instances are terminated when their hardware option is done (or by the reaper if anything is left); the report, raw records, metrics and logs stay in S3 under runs/<id>/."],
];

