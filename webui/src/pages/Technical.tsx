function Preparation({ data }: { data: TechData }) {
  const presets = data.export_presets;
  const fmt = (k: string) => JSON.stringify(presets[k] ?? {});
  return (
    <div className="card mb">
      <h2>What happens to a model before each engine can serve it <Help text="The model files on Hugging Face are PyTorch safetensors. vLLM and PyTorch load them directly; OpenVINO needs its own format (IR), produced once per model and number format by the export image and cached in S3. The thin server receives the model's kind as THIN_TASK." /></h2>
      <div className="grid c2 mt">
        <div className="tile" style={{ cursor: "default" }}>
          <div className="t">vLLM (GPU and AMX CPU) · BF16, W8A8</div>
          <div className="small">No conversion. The pinned safetensors checkpoint is mounted read-only into the container and vLLM loads it; BF16 on the GPU, and on the CPU through vLLM's CPU backend with one thread per physical core (<code>VLLM_CPU_OMP_THREADS_BIND=auto</code>), where oneDNN runs the matrix math on AMX. W8A8 cells use a pre-quantized checkpoint from Hugging Face (a different pinned repository, listed on the model), not a conversion done here.</div>
        </div>
        <div className="tile" style={{ cursor: "default" }}>
          <div className="t">PyTorch (thin server) · BF16</div>
          <div className="small">No conversion. <code>servers/thin</code> loads the checkpoint with Transformers' <code>AutoModelFor*</code> class chosen from the model's kind (<code>THIN_TASK</code>: {Object.entries(data.thin_tasks).map(([k, v]) => `${k} → ${v}`).join(", ")}) in BF16 and serves an OpenAI-style API. On CPU it runs <code>OMP_NUM_THREADS</code> = physical cores with cores pinned; on the GPU the CUDA build of the same image.</div>
        </div>
        <div className="tile" style={{ cursor: "default" }}>
          <div className="t">OpenVINO Model Server · BF16-OV, INT8, INT4 (chat models)</div>
          <div className="small">Converted. The export container runs OVMS's <code>export_model.py</code> on the checkpoint so the model server gets the layout and <code>graph.pbtxt</code> it expects. The number format is the export argument: <code>{fmt("x-ov-bf16")}</code> for BF16-OV (optimum has no BF16 weight format, so the IR is written in FP16 and the CPU plugin runs it in BF16 on AMX; the AMX probe records the precision it actually chose), <code>{fmt("x-ov-int8")}</code> for INT8 and <code>{fmt("x-ov-int4")}</code> for INT4 (nncf weight compression, 128-wide groups, asymmetric). The IR is cached under <code>models/ov/&lt;hash&gt;/</code>; the hash covers the arguments, the source revision and the tool versions.</div>
        </div>
        <div className="tile" style={{ cursor: "default" }}>
          <div className="t">OpenVINO through the thin server · encoder-decoder models and classifiers</div>
          <div className="small">Converted with <code>optimum-cli export openvino</code> (run through <code>optimum_export.py</code>, which lifts the Transformers version caps upstream has already lifted), with the task that fits the model: <code>text2text-generation-with-past</code> for Flan-T5, <code>text-classification</code> for classifiers. The thin OpenVINO image then loads the IR with optimum-intel's <code>OVModelFor*</code> classes. Models the model server does not host (every non-chat model) take this path.</div>
        </div>
      </div>
      <Note kind="warn"><b>A model added under Setup follows the same paths by its kind.</b> Nothing checks in advance that the engine's architecture list includes it; the first run is the proof, and the run page quotes the server's answer when a container refuses the model.</Note>
    </div>
  );
}

function Files({ data }: { data: TechData }) {
  const order = ["servers/thin/Dockerfile.torch", "servers/thin/Dockerfile.openvino", "servers/export/Dockerfile", "webui/Dockerfile", "host/stage_model.sh", "host/serve.sh", "servers/export/export.py", "servers/export/optimum_export.py"];
  return (
    <div className="card mb">
      <h2>The files, verbatim <Help text="Read from the deployed container, so this is the code this build runs; each section opens on click." /></h2>
      {order.filter((k) => data.files[k]).map((k) => {
        const f = data.files[k];
        return (
          <details key={k} className="mt">
            <summary className="small"><b>{k}</b> — {f.title}{f.present ? "" : " (not in this build)"}</summary>
            {f.text && <pre className="small" style={{ background: "var(--bg-3)", border: "1px solid var(--line)", borderRadius: 10, padding: 12, overflow: "auto", maxHeight: 520, fontSize: 11.5, lineHeight: 1.45 }}>{f.text}</pre>}
          </details>
        );
      })}
    </div>
  );
}
